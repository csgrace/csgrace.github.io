const I18N_KEY = 'grace-site-lang';

function getLang() {
  const saved = localStorage.getItem(I18N_KEY);
  if (saved === 'en' || saved === 'zh') return saved;
  const browserLang = navigator.language || '';
  return browserLang.startsWith('zh') ? 'zh' : 'en';
}

function setLang(lang) {
  localStorage.setItem(I18N_KEY, lang);
}

function t(key) {
  const lang = getLang();
  return i18n[lang] && i18n[lang][key] !== undefined ? i18n[lang][key] : (i18n.en[key] || key);
}

function applyI18n() {
  const lang = getLang();

  // Update <html lang>
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';

  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18n[lang] && i18n[lang][key] !== undefined) {
      el.textContent = i18n[lang][key];
    } else if (i18n.en[key] !== undefined) {
      el.textContent = i18n.en[key];
    }
  });

  // Update elements with data-i18n-html (for strings with HTML tags)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (i18n[lang] && i18n[lang][key] !== undefined) {
      el.innerHTML = i18n[lang][key];
    } else if (i18n.en[key] !== undefined) {
      el.innerHTML = i18n.en[key];
    }
  });

  // Update lang switch button text
  const langBtn = document.getElementById('lang-switch');
  if (langBtn) {
    langBtn.textContent = lang === 'zh' ? i18n.zh['lang.switch'] : i18n.en['lang.switch'];
  }

  // Update page title
  const titleEl = document.querySelector('title');
  if (titleEl && titleEl.hasAttribute('data-i18n-title')) {
    const key = titleEl.getAttribute('data-i18n-title');
    const base = lang === 'zh' ? i18n.zh[key] : i18n.en[key];
    document.title = base ? base : (i18n.en[key] || document.title);
  }
}

// Toggle language
function toggleLang() {
  const current = getLang();
  const next = current === 'zh' ? 'en' : 'zh';
  setLang(next);
  applyI18n();
}

// Initialize on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  applyI18n();

  // Bind lang switch button
  const langBtn = document.getElementById('lang-switch');
  if (langBtn) {
    langBtn.addEventListener('click', toggleLang);
  }
});
